#!/usr/bin/env python3
"""Generates the embedded asset headers shared by all platforms.

The song (Dxn_2.xm) is embedded verbatim; minifmod parses it itself from
the byte array. The Windows resource script carries only the application
icon - no demo data is embedded through it.

Run from anywhere:

    py tools/generate_assets.py       (Windows)
    python3 tools/generate_assets.py  (Linux)
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
EMBED_DIR = ROOT / "resources" / "embedded"
BYTES_PER_LINE = 16


def c_array(name: str, data: bytes) -> str:
    lines = []
    for offset in range(0, len(data), BYTES_PER_LINE):
        chunk = data[offset : offset + BYTES_PER_LINE]
        lines.append("    " + ",".join("0x%02x" % b for b in chunk) + ",")
    return "static const unsigned char %s[] = {\n%s\n};" % (name, "\n".join(lines))


def header_body(comment: str, guard: str, body: str) -> str:
    return (
        "// %s\n"
        "// Generated by tools/generate_assets.py - do not edit by hand.\n"
        "#ifndef %s\n"
        "#define %s\n"
        "\n"
        "%s\n"
        "\n"
        "#endif // %s\n"
    ) % (comment, guard, guard, body, guard)


def main() -> None:
    EMBED_DIR.mkdir(parents=True, exist_ok=True)

    song = (ROOT / "resources" / "Dxn_2.xm").read_bytes()

    (EMBED_DIR / "dxn_2.h").write_text(
        header_body(
            "Song data (Dxn_2.xm, embedded verbatim; minifmod parses it itself)",
            "PKISDEAD_EMBEDDED_DNX_2_H",
            c_array("dixiesmod", song),
        ),
        newline="\n",
    )

    print("wrote %s (%d bytes of song data)" % ((EMBED_DIR / "dxn_2.h").relative_to(ROOT), len(song)))


if __name__ == "__main__":
    main()
